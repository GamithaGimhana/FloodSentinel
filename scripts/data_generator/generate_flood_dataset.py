def generate(out):
 out.mkdir(parents=True,exist_ok=True)
 rng=np.random.default_rng(SEED)
 frames=[]; candidate_stats=[]
 for di,(district,lat,lon,elev,wet) in enumerate(DISTRICTS):
  n=24000
  urban=rng.random(n)<(.65 if district in ['Colombo','Gampaha'] else .27)
  land=rng.choice(['Agriculture','Forest','Grassland','Wetland'],n,p=[.48,.22,.2,.1])
  land[urban]='Urban'
  soil=rng.choice(['Clay','Silty','Loamy','Sandy'],n,p=[.28,.23,.34,.15])
  built=np.clip(rng.beta(2,5,n)*70+urban*35,0,98)
  drain=np.clip(rng.beta(2.5,2.5,n)-.15*(land=='Wetland'),.02,.98)
  river=np.clip(rng.lognormal(6.8,1.35,n),5,20000)
  elevation=np.clip(rng.lognormal(np.log(elev+5),.55,n),1,2400)
  hand=np.clip(rng.gamma(1.5,5,n)+river/1500,0,80)
  rain7=np.clip(rng.gamma(2.4,55*wet,n),2,850)
  rain1=rain7*rng.beta(2,5,n)
  rain30=rain7+rng.gamma(2.5,45*wet,n)
  sat=np.clip(.18+.0008*rain30+rng.normal(0,.14,n),.02,.99)
  history=rng.poisson(np.clip(3*np.exp(-river/1700)*(1-drain)+.3,.1,5))
  # Uncalibrated forward simulation: no target is used to construct predictors.
  logit=(-2.6+.011*rain7+1.5*sat-1.25*drain-.12*hand
         +1.1*np.exp(-river/800)+.008*built+.3*(soil=='Clay'))
  prob=1/(1+np.exp(-np.clip(logit,-20,20)))
  y=rng.random(n)<prob
  candidate_stats.append({'district':district,'candidates':n,'flooded':int(y.sum())})
  infra=np.clip(35+urban*22+drain*25+rng.normal(0,12,n),5,98)
  depth=np.where(y,np.clip(rng.gamma(1.6,.35,n)+rain7/900-hand/60,.02,5),0)
  area=np.where(y,np.clip(10000*(1-np.exp(-depth)),1,10000),0)
  ndvi=np.clip(.7-.006*built-.2*y+rng.normal(0,.13,n),-1,1)
  ndwi=np.clip(-.3+.6*y+.25*(land=='Wetland')+rng.normal(0,.18,n),-1,1)
  water=np.where(ndwi>.1,'Likely','Unlikely')
  good=(~y)&(prob<.45)&(infra>=45)
  reason=np.select([y,prob>=.45,infra<45],['Simulated current flooding','High synthetic flood propensity','Low synthetic infrastructure score'],default='Not applicable')
  d=pd.DataFrame({
   'record_id':[f'SL_SYN_D{di+1:02d}_{i:05d}' for i in range(n)],
   'district':district,'place_name':[f'Synthetic site D{di+1:02d}-{i:05d}' for i in range(n)],
   'latitude':lat,'longitude':lon,'elevation_m':np.round(elevation,1),
   'distance_to_river_m':np.round(river,1),'landcover':land,'soil_type':soil,
   'water_supply':np.where(urban,'Municipal',rng.choice(['Well','Municipal','Surface water'],n,p=[.6,.3,.1])),
   'electricity':rng.choice(['Grid','Mixed','Off-grid (solar)','Unavailable'],n,p=[.9,.05,.04,.01]),
   'road_quality':np.select([infra>=70,infra>=45],['Good (paved)','Fair'],default='Poor (unpaved)'),
   'population_density_per_km2':np.round(rng.lognormal(5.4+urban*1.9,.6,n)).astype(int),
   'built_up_percent':np.round(built,1),'urban_rural':np.where(urban,'Urban','Rural'),
   'rainfall_7d_mm':np.round(rain7,1),'monthly_rainfall_mm':np.round(rain30,1),
   'drainage_index':np.round(drain,3),'ndvi':np.round(ndvi,3),'ndwi':np.round(ndwi,3),
   'water_presence_flag':water,'historical_flood_count':history,
   'infrastructure_score':np.round(infra).astype(int),
   'nearest_hospital_km':np.round(np.clip(rng.gamma(2,2.5,n)/(1+urban),.1,40),2),
   'nearest_evac_km':np.round(np.clip(rng.gamma(2,1.4,n),.1,25),2),
   'flood_risk_score':np.round(prob*100,2),'flood_occurrence_current_event':np.where(y,'Yes','No'),
   'inundation_area_sqm':np.round(area,1),'is_good_to_live':np.where(good,'Yes','No'),
   'reason_not_good_to_live':reason,'is_synthetic':True,'generation_date':'2026-09-18',
   'scenario_date':(pd.Timestamp('2026-08-01')+pd.to_timedelta(rng.integers(0,7,n),unit='D')).strftime('%Y-%m-%d'),
   'event_context_id':'AUG2026_MONSOON_REPORT','record_type':'synthetic_site_scenario',
   'coordinate_type':'approximate_district_capital_anchor_not_site',
   'rainfall_24h_mm':np.round(rain1,1),'rainfall_30d_mm':np.round(rain30,1),
   'height_above_nearest_drainage_m':np.round(hand,2),'soil_saturation_index':np.round(sat,3),
   'flood_depth_m':np.round(depth,2),'site_area_sqm':10000,
   'source_context_id':'S1','generator_version':'1.0','random_seed':SEED})
  # Sample WITHOUT replacement, stratified within each district and outcome.
  for label in ['Yes','No']:
   eligible=np.flatnonzero(d.flood_occurrence_current_event.eq(label))
   assert len(eligible)>=2400
   selected=rng.choice(eligible,2400,replace=False)
   part=d.iloc[selected].copy()
   part['split']=np.repeat(['train','validation','test'],[1680,360,360])
   frames.append(part)
 d=pd.concat(frames,ignore_index=True).sample(frac=1,random_state=SEED).reset_index(drop=True)
 filename='sri_lanka_flood_synthetic_balanced_120000.csv'
 path=out/filename
 d.to_csv(path,index=False)
 # Read-back checks test deliverable bytes rather than only in-memory construction.
 check=pd.read_csv(path,keep_default_na=False)
 assert len(check)==120000 and check.record_id.nunique()==120000
 assert check.flood_occurrence_current_event.value_counts().to_dict()=={'Yes':60000,'No':60000} or check.flood_occurrence_current_event.value_counts().to_dict()=={'No':60000,'Yes':60000}
 assert (check.groupby(['district','flood_occurrence_current_event']).size()==2400).all()
 assert (check.rainfall_24h_mm<=check.rainfall_7d_mm).all()
 assert (check.rainfall_7d_mm<=check.rainfall_30d_mm).all()
 assert (check.monthly_rainfall_mm==check.rainfall_30d_mm).all()
 assert ((check.inundation_area_sqm>0)==check.flood_occurrence_current_event.eq('Yes')).all()
 assert ((check.flood_depth_m>0)==check.flood_occurrence_current_event.eq('Yes')).all()
 assert (check.inundation_area_sqm<=check.site_area_sqm).all()
 assert not check.eq('').any().any()
 assert not check.drop(columns=['record_id','place_name']).duplicated().any()
 assert check.is_synthetic.all()
 assert (check.groupby('record_id')['split'].nunique()==1).all()
 excluded=['record_id','place_name','latitude','longitude','ndvi','ndwi','water_presence_flag',
   'flood_risk_score','flood_occurrence_current_event','inundation_area_sqm','is_good_to_live',
   'reason_not_good_to_live','is_synthetic','generation_date','scenario_date','event_context_id',
   'record_type','coordinate_type','monthly_rainfall_mm','flood_depth_m','site_area_sqm',
   'source_context_id','generator_version','random_seed','split']
 recommended=[c for c in d.columns if c not in excluded]
 summary={'rows':len(check),'columns':len(check.columns),'seed':SEED,
  'target':'flood_occurrence_current_event','class_counts':check.flood_occurrence_current_event.value_counts().to_dict(),
  'district_counts':check.district.value_counts().to_dict(),
  'split_counts':check.groupby(['split','flood_occurrence_current_event']).size().unstack().to_dict('index'),
  'secondary_target_counts_NOT_balanced':check.is_good_to_live.value_counts().to_dict(),
  'candidate_counts_before_balancing':candidate_stats,
  'recommended_predictors':recommended,'excluded_from_predictors':excluded,
  'checks_passed':['unique IDs','120000 rows','exact target balance per district',
  'rainfall ordering','positive depth and area iff flooded','area <= site area',
  'no empty fields','no duplicate scenarios excluding IDs','all synthetic','disjoint site IDs across splits'],
  'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
